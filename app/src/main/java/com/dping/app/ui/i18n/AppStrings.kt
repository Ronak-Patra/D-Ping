object AppStringsProvider {
    fun getStrings(code: String): AppStrings {
        return when (code.lowercase()) {
            // Indian Languages (14)
            "hi" -> HindiStrings
            "bn" -> BengaliStrings
            "pa" -> PunjabiStrings
            "mr" -> MarathiStrings
            "gu" -> GujaratiStrings
            "ta" -> TamilStrings
            "te" -> TeluguStrings
            "kn" -> KannadaStrings
            "ml" -> MalayalamStrings
            "or" -> OdiaStrings
            "as" -> AssameseStrings
            "ur" -> UrduStrings
            "ne" -> NepaliStrings
            "sa" -> SanskritStrings

            // Global Languages (9)
            "en" -> EnglishStrings
            "es" -> SpanishStrings
            "zh", "zh-cn", "zh-tw" -> ChineseStrings
            "de" -> GermanStrings
            "fr" -> FrenchStrings
            "ru" -> RussianStrings
            "he", "iw" -> HebrewStrings
            "tr" -> TurkishStrings
            "ko" -> KoreanStrings

            // Additional Regional
            "in", "id" -> IndonesianStrings
            "it" -> ItalianStrings
            "pt" -> PortugueseStrings
            "vi" -> VietnameseStrings
            else -> EnglishStrings
        }
    }
}

val LocalAppStrings = staticCompositionLocalOf { EnglishStrings }
